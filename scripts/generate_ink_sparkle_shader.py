#!/usr/bin/env python3
"""Translate the pinned Material InkSparkle GLSL to a Skia runtime effect.

Run after changing the material_ui pin. Only syntax/entrypoint plumbing changes;
the uniform declaration order and every shader expression stay upstream-owned.
Flutter uses the same local-coordinate entrypoint in spirv_sksl.cc.
"""

from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "material-ui-src/lib/src/shaders/ink_sparkle.frag"
TARGET = ROOT / "src/Plumix.Material/Assets/Shaders/ink_sparkle.sksl"
ORACLE_SOURCE = ROOT / "flutter-src/engine/src/flutter/lib/web_ui/test/canvaskit/fragment_program_test.dart"
ORACLE_TARGET = ROOT / "src/Plumix.Tests/Fixtures/Shaders/ink_sparkle_flutter.sksl"


def generate() -> str:
    source = SOURCE.read_text(encoding="utf-8")
    source = re.sub(r"^#version.*\n|^precision.*\n|^#include.*\n", "", source, flags=re.M)
    source = re.sub(r"layout\(location = \d+\) uniform", "uniform", source)
    source = source.replace("layout(location = 0) out vec4 fragColor;", "")
    for name, component in [("u_alpha", "x"), ("u_sparkle_alpha", "y"),
                            ("u_blur", "z"), ("u_radius_scale", "w")]:
        source = source.replace(f"float {name} = u_composite_1.{component};", "")
        source = re.sub(rf"\b{name}\b", f"u_composite_1.{component}", source)
    source = source.replace("highp ", "")
    source = source.replace("void main()", "half4 main(float2 coordinate)")
    source = source.replace("FlutterFragCoord()", "coordinate")
    source = source.replace("fragColor =", "return")
    # Local variable names in main may shadow the original GLSL function names.
    for name in ["turbulence", "sparkle"]:
        source = re.sub(rf"\b{name}\(", f"flutter_{name}(", source)
    return ("// Generated by scripts/generate_ink_sparkle_shader.py; do not edit.\n"
            "// Dart parity source: material_ui/lib/src/shaders/ink_sparkle.frag\n" + source)


if __name__ == "__main__":
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"Generated {TARGET.relative_to(ROOT)}")
    # Independent, spirv-cross-generated upstream oracle. Its older uniform layout has a separate
    # sparkle colour; tests bind opaque white to reproduce the pinned GLSL's vec4(1.0).
    fixture = ORACLE_SOURCE.read_text(encoding="utf-8")
    match = re.search(r"const String kJsonIPLR = r'''(.*?)''';", fixture, re.S)
    if match is None:
        raise ValueError("Flutter's compiled InkSparkle fixture was not found")
    oracle = json.loads(match[1])["sksl"]["shader"]
    ORACLE_TARGET.parent.mkdir(parents=True, exist_ok=True)
    ORACLE_TARGET.write_text(
        "// Copyright 2013 The Flutter Authors. BSD-style license; see LICENSE.\n"
        "// Generated by scripts/generate_ink_sparkle_shader.py from Flutter's CanvasKit test fixture.\n"
        + oracle, encoding="utf-8", newline="\n")
    print(f"Generated {ORACLE_TARGET.relative_to(ROOT)}")
    for directory in [TARGET.parent, ORACLE_TARGET.parent]:
        (directory / "LICENSE").write_text(
            (ROOT / "flutter-src/LICENSE").read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
