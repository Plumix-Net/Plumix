// C#-only infrastructure: the Avalonia host's analogue of Flutter's per-embedding
// `keyboard_maps.g.dart`. Flutter generates one scan-code table per embedding (Android, GTK, Web,
// Windows, ...); Plumix has a single Avalonia host, whose `PhysicalKey` enum already uses the W3C
// `code` names that Flutter's `PhysicalKeyboardKey` constants are named after, so the physical map
// is resolved by name and only the layout-independent `Key` -> logical map is spelled out.

using Avalonia.Input;
using Plumix.UI;

