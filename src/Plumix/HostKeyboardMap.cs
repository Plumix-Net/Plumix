    /// <summary>
    /// The plane for keys Avalonia reports that Flutter has no constant for. Flutter reserves one
    /// plane per embedding above `LogicalKeyboardKey.StartOfPlatformPlanes` (android 0x011 through
    /// glfw 0x018); 0x019 is the next free value and is Plumix's Avalonia plane. Keys synthesized
    /// into it report `IsAutogenerated == true`, exactly like Flutter's platform-plane keys.
    /// </summary>
    internal const long AvaloniaPlane = 0x01900000000;

    /// <summary>
    /// Physical keys Avalonia knows but Flutter has no USB HID constant for are synthesized above
    /// the USB HID range so that they stay unique in `HardwareKeyboard`'s pressed-key map.
    /// </summary>
    private const long SynthesizedPhysicalBase = 0x10000000000;

    public static PhysicalKeyboardKey PhysicalKeyFor(PhysicalKey physicalKey)
    {
        string? name = Enum.GetName(physicalKey);
        if (name == null || physicalKey == PhysicalKey.None)
        {
            return new PhysicalKeyboardKey(SynthesizedPhysicalBase + (long)physicalKey);
        }

        // Avalonia spells the letter keys `A`..`Z` and the numeric pad `NumPadN`; Flutter's
        // constants are `KeyA`..`KeyZ` and `NumpadN`.
        string normalized = name.Length == 1 && char.IsAsciiLetter(name[0])
            ? $"Key{name}"
            : name.StartsWith("NumPad", StringComparison.Ordinal)
                ? string.Concat("Numpad", name.AsSpan(6))
                : name;

        return PhysicalKeyboardKey.FindKeyByGeneratedName(normalized)
               ?? new PhysicalKeyboardKey(SynthesizedPhysicalBase + (long)physicalKey);
    }

    public static LogicalKeyboardKey LogicalKeyFor(Key key, string? keySymbol)
    {
        LogicalKeyboardKey? mapped = MapLogicalKey(key);
        if (mapped != null)
        {
            return mapped;
        }

        // Keys Avalonia does not name fall back to the character the layout produced, which is how
        // Flutter's embedders resolve logical keys that are not in their scan-code table.
        if (keySymbol is { Length: > 0 })
        {
            string lowered = keySymbol.ToLowerInvariant();
            if (char.IsHighSurrogate(lowered[0]) ? lowered.Length == 2 : lowered.Length == 1)
            {
                int rune = char.ConvertToUtf32(lowered, 0);
                if (!LogicalKeyboardKey.IsControlCharacter(lowered))
                {
                    return LogicalKeyboardKey.FindKeyByKeyId(rune) ?? new LogicalKeyboardKey(rune);
                }
            }
        }

        return new LogicalKeyboardKey(AvaloniaPlane + (long)key);
    }

    public static KeyEventDeviceType DeviceTypeFor(KeyDeviceType deviceType)
    {
        return deviceType switch
        {
            KeyDeviceType.Gamepad => KeyEventDeviceType.Gamepad,
            KeyDeviceType.Remote => KeyEventDeviceType.Hdmi,
            _ => KeyEventDeviceType.Keyboard,
        };
    }

