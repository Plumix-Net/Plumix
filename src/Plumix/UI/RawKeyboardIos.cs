using System.Diagnostics;
using Plumix.Foundation;

namespace Plumix.UI;

/// <summary>
/// Platform-specific key event data for iOS, obtained from iOS' <c>UIKey</c> interface.
/// </summary>
/// <remarks>
/// This class is deprecated and will be removed. Platform specific key event data will no longer
/// be available. See <c>KeyEvent</c> for what is available.
/// </remarks>
[Obsolete(
    "Platform specific key event data is no longer available. See KeyEvent for what is available. "
    + "Mirrors Flutter's deprecation after v3.18.0-2.0.pre.")]
public class RawKeyEventDataIos : RawKeyEventData
{
    /// <summary>Creates a key event data structure specific for iOS.</summary>
    public RawKeyEventDataIos(
        string characters = "",
        string charactersIgnoringModifiers = "",
        int keyCode = 0,
        int modifiers = 0)
    {
        Characters = characters;
        CharactersIgnoringModifiers = charactersIgnoringModifiers;
        KeyCode = keyCode;
        Modifiers = modifiers;
    }

    /// <summary>The Unicode characters associated with a key-up or key-down event.</summary>
    public string Characters { get; }

    /// <summary>The characters generated by a key event as if no modifier key (except for Shift) applies.</summary>
    public string CharactersIgnoringModifiers { get; }

    /// <summary>The virtual key code for the keyboard key associated with a key event.</summary>
    public int KeyCode { get; }

    /// <summary>A mask of the current modifiers using the values in Modifier Flags.</summary>
    public int Modifiers { get; }

    /// <inheritdoc/>
    public override string KeyLabel => CharactersIgnoringModifiers;

    /// <inheritdoc/>
    public override PhysicalKeyboardKey PhysicalKey =>
        KeyboardMaps.KIosToPhysicalKey.GetValueOrDefault(KeyCode)
        ?? new PhysicalKeyboardKey(LogicalKeyboardKey.IosPlane + KeyCode);

    /// <inheritdoc/>
    public override LogicalKeyboardKey LogicalKey
    {
        get
        {
            // Look to see if the keyCode is a printable number pad key, so that a difference between
            // regular keys (e.g. "=") and the number pad version (e.g. the "=" on the number pad) can
            // be determined.
            LogicalKeyboardKey? numPadKey = KeyboardMaps.KIosNumPadMap.GetValueOrDefault(KeyCode);
            if (numPadKey != null)
            {
                return numPadKey;
            }

            // Look to see if the [keyLabel] is one we know about and have a mapping for.
            string keyLabel = KeyLabel;
            LogicalKeyboardKey? specialKey = KeyboardMaps.KIosSpecialLogicalMap.GetValueOrDefault(keyLabel);
            if (specialKey != null)
            {
                return specialKey;
            }

            // Keys that can't be derived with characterIgnoringModifiers will be derived from their
            // key codes using this map.
            LogicalKeyboardKey? knownKey = KeyboardMaps.KIosToLogicalKey.GetValueOrDefault(KeyCode);
            if (knownKey != null)
            {
                return knownKey;
            }

            // If this key is printable, generate the LogicalKeyboardKey from its Unicode value.
            // Control keys such as ESC, CTRL, and SHIFT are not printable. HOME, DEL, arrow keys, and
            // function keys are considered modifier function keys, which generate invalid Unicode
            // scalar values.
            if (keyLabel.Length != 0
                && !LogicalKeyboardKey.IsControlCharacter(keyLabel)
                && !IsUnprintableKey(keyLabel))
            {
                // Given that charactersIgnoringModifiers can contain a String of arbitrary length,
                // limit to a maximum of two Unicode scalar values. It is unlikely that a keyboard would
                // produce a code point bigger than 32 bits, but it is still worth defending against
                // this case.
                Debug.Assert(CharactersIgnoringModifiers.Length <= 2);
                int codeUnit = CharactersIgnoringModifiers[0];
                if (CharactersIgnoringModifiers.Length == 2)
                {
                    int secondCode = CharactersIgnoringModifiers[1];
                    codeUnit = (codeUnit << 16) | secondCode;
                }

                long keyId = LogicalKeyboardKey.UnicodePlane | (codeUnit & LogicalKeyboardKey.ValueMask);
                return LogicalKeyboardKey.FindKeyByKeyId(keyId) ?? new LogicalKeyboardKey(keyId);
            }

            // This is a non-printable key that we don't know about, so we mint a new code.
            return new LogicalKeyboardKey(KeyCode | LogicalKeyboardKey.IosPlane);
        }
    }

    /// <summary>
    /// Returns true if the given label represents an unprintable key, e.g.
    /// "NSUpArrowFunctionKey = 0xF700" or "NSHomeFunctionKey = 0xF729".
    /// </summary>
    private static bool IsUnprintableKey(string label)
    {
        if (label.Length != 1)
        {
            return false;
        }

        int codeUnit = label[0];
        return codeUnit >= 0xF700 && codeUnit <= 0xF8FF;
    }

    private bool IsLeftRightModifierPressed(KeyboardSide side, int anyMask, int leftMask, int rightMask)
    {
        if ((Modifiers & anyMask) == 0)
        {
            return false;
        }

        if ((Modifiers & (leftMask | rightMask | anyMask)) == anyMask)
        {
            // If only the "anyMask" bit is set, then we respond true for requests of whether either
            // left or right is pressed. Handles the case where iOS supplies just the "either" modifier
            // flag, but not the left/right flag. (e.g. modifierShift but not modifierLeftShift).
            return true;
        }

        return side switch
        {
            KeyboardSide.Any => true,
            KeyboardSide.All => (Modifiers & leftMask) != 0 && (Modifiers & rightMask) != 0,
            KeyboardSide.Left => (Modifiers & leftMask) != 0,
            KeyboardSide.Right => (Modifiers & rightMask) != 0,
            _ => throw new ArgumentOutOfRangeException(nameof(side)),
        };
    }

    /// <inheritdoc/>
    public override bool IsModifierPressed(ModifierKey key, KeyboardSide side = KeyboardSide.Any)
    {
        int independentModifier = unchecked((int)(Modifiers & DeviceIndependentMask));
        bool result;
        switch (key)
        {
            case ModifierKey.ControlModifier:
                result = IsLeftRightModifierPressed(
                    side,
                    independentModifier & ModifierControl,
                    ModifierLeftControl,
                    ModifierRightControl);
                break;
            case ModifierKey.ShiftModifier:
                result = IsLeftRightModifierPressed(
                    side,
                    independentModifier & ModifierShift,
                    ModifierLeftShift,
                    ModifierRightShift);
                break;
            case ModifierKey.AltModifier:
                result = IsLeftRightModifierPressed(
                    side,
                    independentModifier & ModifierOption,
                    ModifierLeftOption,
                    ModifierRightOption);
                break;
            case ModifierKey.MetaModifier:
                result = IsLeftRightModifierPressed(
                    side,
                    independentModifier & ModifierCommand,
                    ModifierLeftCommand,
                    ModifierRightCommand);
                break;
            case ModifierKey.CapsLockModifier:
                result = (independentModifier & ModifierCapsLock) != 0;
                break;
            // On iOS, the function modifier bit is set for any function key, like F1, F2, etc., but
            // the meaning of ModifierKey.modifierFunction in Flutter is that of the Fn modifier key,
            // so there's no good way to emulate that on iOS.
            case ModifierKey.FunctionModifier:
            case ModifierKey.NumLockModifier:
            case ModifierKey.SymbolModifier:
            case ModifierKey.ScrollLockModifier:
                // These modifier masks are not used in iOS keyboards.
                result = false;
                break;
            default:
                throw new ArgumentOutOfRangeException(nameof(key));
        }

        Debug.Assert(
            !result || GetModifierSide(key) != null,
            $"{GetType().Name} thinks that a modifier is pressed, but can't figure out what side it's on.");
        return result;
    }

    /// <inheritdoc/>
    public override KeyboardSide? GetModifierSide(ModifierKey key)
    {
        KeyboardSide? FindSide(int anyMask, int leftMask, int rightMask)
        {
            int combinedMask = leftMask | rightMask;
            int combined = Modifiers & combinedMask;
            if (combined == leftMask)
            {
                return KeyboardSide.Left;
            }
            else if (combined == rightMask)
            {
                return KeyboardSide.Right;
            }
            else if (combined == combinedMask || (Modifiers & (combinedMask | anyMask)) == anyMask)
            {
                // Handles the case where iOS supplies just the "either" modifier flag, but not the
                // left/right flag. (e.g. modifierShift but not modifierLeftShift), or if left and
                // right flags are provided, but not the "either" modifier flag.
                return KeyboardSide.All;
            }

            return null;
        }

        switch (key)
        {
            case ModifierKey.ControlModifier:
                return FindSide(ModifierControl, ModifierLeftControl, ModifierRightControl);
            case ModifierKey.ShiftModifier:
                return FindSide(ModifierShift, ModifierLeftShift, ModifierRightShift);
            case ModifierKey.AltModifier:
                return FindSide(ModifierOption, ModifierLeftOption, ModifierRightOption);
            case ModifierKey.MetaModifier:
                return FindSide(ModifierCommand, ModifierLeftCommand, ModifierRightCommand);
            case ModifierKey.CapsLockModifier:
            case ModifierKey.NumLockModifier:
            case ModifierKey.ScrollLockModifier:
            case ModifierKey.FunctionModifier:
            case ModifierKey.SymbolModifier:
                return KeyboardSide.All;
            default:
                throw new ArgumentOutOfRangeException(nameof(key));
        }
    }

    /// <inheritdoc/>
    public override void DebugFillProperties(DiagnosticPropertiesBuilder properties)
    {
        base.DebugFillProperties(properties);
        properties.Add(new DiagnosticsProperty<string>("characters", Characters));
        properties.Add(
            new DiagnosticsProperty<string>("charactersIgnoringModifiers", CharactersIgnoringModifiers));
        properties.Add(new DiagnosticsProperty<int>("keyCode", KeyCode));
        properties.Add(new DiagnosticsProperty<int>("modifiers", Modifiers));
    }

    /// <inheritdoc/>
    public override bool Equals(object? obj)
    {
        if (ReferenceEquals(this, obj))
        {
            return true;
        }

        if (obj is null || obj.GetType() != GetType())
        {
            return false;
        }

        return obj is RawKeyEventDataIos other
            && other.Characters == Characters
            && other.CharactersIgnoringModifiers == CharactersIgnoringModifiers
            && other.KeyCode == KeyCode
            && other.Modifiers == Modifiers;
    }

    /// <inheritdoc/>
    public override int GetHashCode() =>
        HashCode.Combine(Characters, CharactersIgnoringModifiers, KeyCode, Modifiers);

    // Modifier key masks. See Apple's UIKey documentation
    // https://developer.apple.com/documentation/uikit/uikeymodifierflags?language=objc
    // https://opensource.apple.com/source/IOHIDFamily/IOHIDFamily-86/IOHIDSystem/IOKit/hidsystem/IOLLEvent.h.auto.html

    /// <summary>Mask for <see cref="Modifiers"/>: the CAPS LOCK modifier key is on.</summary>
    public const int ModifierCapsLock = 0x10000;

    /// <summary>Mask for <see cref="Modifiers"/>: one of the SHIFT modifier keys is pressed.</summary>
    public const int ModifierShift = 0x20000;

    /// <summary>Mask for <see cref="Modifiers"/>: the left SHIFT modifier key is pressed.</summary>
    public const int ModifierLeftShift = 0x02;

    /// <summary>Mask for <see cref="Modifiers"/>: the right SHIFT modifier key is pressed.</summary>
    public const int ModifierRightShift = 0x04;

    /// <summary>Mask for <see cref="Modifiers"/>: one of the CTRL modifier keys is pressed.</summary>
    public const int ModifierControl = 0x40000;

    /// <summary>Mask for <see cref="Modifiers"/>: the left CTRL modifier key is pressed.</summary>
    public const int ModifierLeftControl = 0x01;

    /// <summary>Mask for <see cref="Modifiers"/>: the right CTRL modifier key is pressed.</summary>
    public const int ModifierRightControl = 0x2000;

    /// <summary>Mask for <see cref="Modifiers"/>: one of the ALT modifier keys is pressed.</summary>
    public const int ModifierOption = 0x80000;

    /// <summary>Mask for <see cref="Modifiers"/>: the left ALT modifier key is pressed.</summary>
    public const int ModifierLeftOption = 0x20;

    /// <summary>Mask for <see cref="Modifiers"/>: the right ALT modifier key is pressed.</summary>
    public const int ModifierRightOption = 0x40;

    /// <summary>Mask for <see cref="Modifiers"/>: one of the CMD modifier keys is pressed.</summary>
    public const int ModifierCommand = 0x100000;

    /// <summary>Mask for <see cref="Modifiers"/>: the left CMD modifier key is pressed.</summary>
    public const int ModifierLeftCommand = 0x08;

    /// <summary>Mask for <see cref="Modifiers"/>: the right CMD modifier key is pressed.</summary>
    public const int ModifierRightCommand = 0x10;

    /// <summary>Mask for <see cref="Modifiers"/>: any key in the numeric keypad is pressed.</summary>
    public const int ModifierNumericPad = 0x200000;

    /// <summary>Mask for <see cref="Modifiers"/>: the HELP modifier key is pressed.</summary>
    public const int ModifierHelp = 0x400000;

    /// <summary>Mask for <see cref="Modifiers"/>: one of the FUNCTION modifier keys is pressed.</summary>
    public const int ModifierFunction = 0x800000;

    /// <summary>
    /// Used to retrieve only the device-independent modifier flags, allowing applications to mask
    /// off the device-dependent modifier flags, including event coalescing information.
    /// </summary>
    /// <remarks>
    /// <c>long</c> rather than <c>int</c>: Dart's 64-bit <c>int</c> holds 0xffff0000 as a positive
    /// value, which does not fit a C# <c>int</c>.
    /// </remarks>
    public const long DeviceIndependentMask = 0xffff0000;
}
