/// <summary>
/// Platform-specific key event data for Linux. Different window toolkit implementations can map to
/// different key codes; this class uses the mapping of the <see cref="KeyHelper"/> provided.
/// </summary>
[Obsolete(
    "Platform specific key event data is no longer available. See KeyEvent for what is available. "
    + "Mirrors Flutter's deprecation after v3.18.0-2.0.pre.")]
public class RawKeyEventDataLinux : RawKeyEventData
{
    /// <summary>Creates a key event data structure specific for Linux.</summary>
    /// <remarks>Dart's required named <c>isDown</c> moves up next to <c>keyHelper</c> (C# optionals go last).</remarks>
    [Obsolete(
        "Platform specific key event data is no longer available. See KeyEvent for what is available. "
        + "Mirrors Flutter's deprecation after v3.18.0-2.0.pre.")]
    public RawKeyEventDataLinux(
        KeyHelper keyHelper,
        bool isDown,
        long unicodeScalarValues = 0,
        int scanCode = 0,
        int keyCode = 0,
        int modifiers = 0,
        long? specifiedLogicalKey = null)
    {
        ArgumentNullException.ThrowIfNull(keyHelper);
        DebugAssertions.Assert((unicodeScalarValues & ~LogicalKeyboardKey.ValueMask) == 0);
        KeyHelper = keyHelper;
        UnicodeScalarValues = unicodeScalarValues;
        ScanCode = scanCode;
        KeyCode = keyCode;
        Modifiers = modifiers;
        IsDown = isDown;
        SpecifiedLogicalKey = specifiedLogicalKey;
    }

    /// <summary>A helper class that abstracts the fetching of the toolkit-specific mappings.</summary>
    public KeyHelper KeyHelper { get; }

    /// <summary>An int with up to two Unicode scalar values generated by a single keystroke.</summary>
    /// <remarks>
    /// <see langword="long"/> like Dart's 64-bit <c>int</c>, so the constructor's
    /// <c>valueMask</c> assertion can reject values wider than 32 bits.
    /// </remarks>
    public long UnicodeScalarValues { get; }

    /// <summary>The hardware scan code id corresponding to this key event.</summary>
    public int ScanCode { get; }

    /// <summary>The hardware key code corresponding to this key event (toolkit-dependent).</summary>
    public int KeyCode { get; }

    /// <summary>A mask of the current modifiers (toolkit-dependent).</summary>
    public int Modifiers { get; }

    /// <summary>Whether or not this key event is a key down (true) or key up (false).</summary>
    public bool IsDown { get; }

    /// <summary>
    /// A logical key specified by the embedding that should be used instead of deriving from raw data.
    /// </summary>
    public long? SpecifiedLogicalKey { get; }

    /// <inheritdoc />
    public override string KeyLabel =>
        UnicodeScalarValues == 0 ? string.Empty : FromCharCode(checked((int)UnicodeScalarValues));

    /// <inheritdoc />
    public override PhysicalKeyboardKey PhysicalKey =>
        KeyboardMaps.KLinuxToPhysicalKey.GetValueOrDefault(ScanCode)
        ?? new PhysicalKeyboardKey(LogicalKeyboardKey.WebPlane + ScanCode);

    /// <inheritdoc />
    public override LogicalKeyboardKey LogicalKey
    {
        get
        {
            if (SpecifiedLogicalKey != null)
            {
                long key = SpecifiedLogicalKey.Value;
                return LogicalKeyboardKey.FindKeyByKeyId(key) ?? new LogicalKeyboardKey(key);
            }

            // Look to see if the keyCode is a printable number pad key, so that a
            // difference between regular keys (e.g. "=") and the number pad version
            // (e.g. the "=" on the number pad) can be determined.
            LogicalKeyboardKey? numPadKey = KeyHelper.NumpadKey(KeyCode);
            if (numPadKey != null)
            {
                return numPadKey;
            }

            // If it has a non-control-character label, then either return the existing
            // constant, or construct a new Unicode-based key from it. Don't mark it as
            // autogenerated, since the label uniquely identifies an ID from the Unicode
            // plane.
            if (KeyLabel.Length != 0 && !LogicalKeyboardKey.IsControlCharacter(KeyLabel))
            {
                long keyId = LogicalKeyboardKey.UnicodePlane | (UnicodeScalarValues & LogicalKeyboardKey.ValueMask);
                return LogicalKeyboardKey.FindKeyByKeyId(keyId) ?? new LogicalKeyboardKey(keyId);
            }

            // Look to see if the keyCode is one we know about and have a mapping for.
            LogicalKeyboardKey? newKey = KeyHelper.LogicalKey(KeyCode);
            if (newKey != null)
            {
                return newKey;
            }

            // This is a non-printable key that we don't know about, so we mint a new
            // code.
            return new LogicalKeyboardKey((long)KeyCode | KeyHelper.PlatformPlane);
        }
    }

    /// <inheritdoc />
    public override bool IsModifierPressed(ModifierKey key, KeyboardSide side = KeyboardSide.Any)
    {
        return KeyHelper.IsModifierPressed(key, Modifiers, side: side, keyCode: KeyCode, isDown: IsDown);
    }

    /// <inheritdoc />
    public override KeyboardSide? GetModifierSide(ModifierKey key)
    {
        return KeyHelper.GetModifierSide(key);
    }

    /// <inheritdoc />
    public override void DebugFillProperties(DiagnosticPropertiesBuilder properties)
    {
        base.DebugFillProperties(properties);
        properties.Add(new DiagnosticsProperty<string>("toolkit", KeyHelper.DebugToolkit));
        properties.Add(new DiagnosticsProperty<long>("unicodeScalarValues", UnicodeScalarValues));
        properties.Add(new DiagnosticsProperty<int>("scanCode", ScanCode));
        properties.Add(new DiagnosticsProperty<int>("keyCode", KeyCode));
        properties.Add(new DiagnosticsProperty<int>("modifiers", Modifiers));
        properties.Add(new DiagnosticsProperty<bool>("isDown", IsDown));
        properties.Add(new DiagnosticsProperty<long?>(
            "specifiedLogicalKey",
            SpecifiedLogicalKey,
            defaultValue: DiagnosticsDefaults.NullValue));
    }

    /// <inheritdoc />
    public override bool Equals(object? obj)
    {
        if (ReferenceEquals(this, obj))
        {
            return true;
        }

        if (obj is null || obj.GetType() != GetType())
        {
            return false;
        }

        return obj is RawKeyEventDataLinux other
            && other.KeyHelper.GetType() == KeyHelper.GetType()
            && other.UnicodeScalarValues == UnicodeScalarValues
            && other.ScanCode == ScanCode
            && other.KeyCode == KeyCode
            && other.Modifiers == Modifiers
            && other.IsDown == IsDown;
    }

    /// <inheritdoc />
    public override int GetHashCode() =>
        HashCode.Combine(KeyHelper.GetType(), UnicodeScalarValues, ScanCode, KeyCode, Modifiers, IsDown);

    /// <summary>Dart's <c>String.fromCharCode</c>: one UTF-16 code unit, or a surrogate pair above the BMP.</summary>
    private static string FromCharCode(int charCode) =>
        (uint)charCode <= 0xFFFF ? ((char)charCode).ToString() : char.ConvertFromUtf32(charCode);
}

/// <summary>
/// Abstract class for window-specific key mappings, giving a common interface over the different
/// window toolkits (GLFW, GTK, QT, etc).
/// </summary>
[Obsolete("No longer supported. Mirrors Flutter's deprecation after v3.18.0-2.0.pre.")]
public abstract class KeyHelper
{
    /// <summary>
    /// C#-only: Dart's <c>KeyHelper</c> declares only a factory constructor and is implemented, not
    /// extended; C# subclasses need an accessible constructor.
    /// </summary>
    protected KeyHelper()
    {
    }

    /// <summary>Create a KeyHelper implementation depending on the given toolkit.</summary>
    /// <remarks>Dart's <c>factory KeyHelper(String toolkit)</c>.</remarks>
    [Obsolete("No longer supported. Mirrors Flutter's deprecation after v3.18.0-2.0.pre.")]
    public static KeyHelper Create(string toolkit)
    {
        if (toolkit == "glfw")
        {
            return new GLFWKeyHelper();
        }
        else if (toolkit == "gtk")
        {
            return new GtkKeyHelper();
        }
        else
        {
            throw new FlutterError($"Window toolkit not recognized: {toolkit}");
        }
    }

    /// <summary>Returns the name for the toolkit, used in debug mode to generate readable strings.</summary>
    public abstract string DebugToolkit { get; }

    /// <summary>
    /// Returns a <see cref="KeyboardSide"/> value that describes which side or sides of the given
    /// keyboard modifier key were pressed at the time of this event.
    /// </summary>
    [Obsolete("No longer supported. Mirrors Flutter's deprecation after v3.18.0-2.0.pre.")]
    public abstract KeyboardSide GetModifierSide(ModifierKey key);

    /// <summary>Returns true if the given <see cref="ModifierKey"/> was pressed at the time of this event.</summary>
    /// <remarks>
    /// Dart's required named <c>keyCode</c>/<c>isDown</c> follow the optional <c>side</c>; C# needs
    /// optional parameters last, so <c>side</c> moves to the end.
    /// </remarks>
    [Obsolete("No longer supported. Mirrors Flutter's deprecation after v3.18.0-2.0.pre.")]
    public abstract bool IsModifierPressed(
        ModifierKey key,
        int modifiers,
        int keyCode,
        bool isDown,
        KeyboardSide side = KeyboardSide.Any);

    /// <summary>The numpad key from the specific key code mapping.</summary>
    public abstract LogicalKeyboardKey? NumpadKey(int keyCode);

    /// <summary>The logical key from the specific key code mapping.</summary>
    public abstract LogicalKeyboardKey? LogicalKey(int keyCode);

    /// <summary>The platform plane mask value of this platform.</summary>
    public abstract long PlatformPlane { get; }
}

/// <summary>Helper class that uses GLFW-specific key mappings.</summary>
[Obsolete("No longer supported. Mirrors Flutter's deprecation after v3.18.0-2.0.pre.")]
public class GLFWKeyHelper : KeyHelper
{
    /// <summary>Mask on <see cref="RawKeyEventDataLinux.Modifiers"/> for whether CAPS LOCK is on.</summary>
    public const int ModifierCapsLock = 0x0010;

    /// <summary>Mask on <see cref="RawKeyEventDataLinux.Modifiers"/> for whether a SHIFT key is pressed.</summary>
    public const int ModifierShift = 0x0001;

    /// <summary>Mask on <see cref="RawKeyEventDataLinux.Modifiers"/> for whether a CTRL key is pressed.</summary>
    public const int ModifierControl = 0x0002;

    /// <summary>Mask on <see cref="RawKeyEventDataLinux.Modifiers"/> for whether an ALT key is pressed.</summary>
    public const int ModifierAlt = 0x0004;

    /// <summary>Mask on <see cref="RawKeyEventDataLinux.Modifiers"/> for whether a META (SUPER) key is down.</summary>
    public const int ModifierMeta = 0x0008;

    /// <summary>
    /// Mask on <see cref="RawKeyEventDataLinux.Modifiers"/> for whether a numeric keypad key is pressed.
    /// </summary>
    public const int ModifierNumericPad = 0x0020;

    /// <inheritdoc />
    public override string DebugToolkit => "GLFW";

    private static int MergeModifiers(int modifiers, int keyCode, bool isDown)
    {
        // GLFW Key codes for modifier keys.
        const int shiftLeftKeyCode = 340;
        const int shiftRightKeyCode = 344;
        const int controlLeftKeyCode = 341;
        const int controlRightKeyCode = 345;
        const int altLeftKeyCode = 342;
        const int altRightKeyCode = 346;
        const int metaLeftKeyCode = 343;
        const int metaRightKeyCode = 347;
        const int capsLockKeyCode = 280;
        const int numLockKeyCode = 282;

        // On GLFW, the "modifiers" bitfield is the state as it is BEFORE this event
        // happened, not AFTER, like every other platform. Consequently, if this is
        // a key down, then we need to add the correct modifier bits, and if it's a
        // key up, we need to remove them.

        int modifierChange = keyCode switch
        {
            shiftLeftKeyCode or shiftRightKeyCode => ModifierShift,
            controlLeftKeyCode or controlRightKeyCode => ModifierControl,
            altLeftKeyCode or altRightKeyCode => ModifierAlt,
            metaLeftKeyCode or metaRightKeyCode => ModifierMeta,
            capsLockKeyCode => ModifierCapsLock,
            numLockKeyCode => ModifierNumericPad,
            _ => 0,
        };

        return isDown ? modifiers | modifierChange : modifiers & ~modifierChange;
    }

    /// <inheritdoc />
    [Obsolete("No longer supported. Mirrors Flutter's deprecation after v3.18.0-2.0.pre.")]
    public override bool IsModifierPressed(
        ModifierKey key,
        int modifiers,
        int keyCode,
        bool isDown,
        KeyboardSide side = KeyboardSide.Any)
    {
        modifiers = MergeModifiers(modifiers: modifiers, keyCode: keyCode, isDown: isDown);
        return key switch
        {
            ModifierKey.ControlModifier => (modifiers & ModifierControl) != 0,
            ModifierKey.ShiftModifier => (modifiers & ModifierShift) != 0,
            ModifierKey.AltModifier => (modifiers & ModifierAlt) != 0,
            ModifierKey.MetaModifier => (modifiers & ModifierMeta) != 0,
            ModifierKey.CapsLockModifier => (modifiers & ModifierCapsLock) != 0,
            ModifierKey.NumLockModifier => (modifiers & ModifierNumericPad) != 0,
            // These are not used in GLFW keyboards.
            ModifierKey.FunctionModifier => false,
            ModifierKey.SymbolModifier => false,
            ModifierKey.ScrollLockModifier => false,
            _ => throw new ArgumentOutOfRangeException(nameof(key)),
        };
    }

    /// <inheritdoc />
    [Obsolete("No longer supported. Mirrors Flutter's deprecation after v3.18.0-2.0.pre.")]
    public override KeyboardSide GetModifierSide(ModifierKey key)
    {
        // Neither GLFW nor X11 provide a distinction between left and right
        // modifiers, so defaults to KeyboardSide.all.
        // https://code.woboq.org/qt5/include/X11/X.h.html#_M/ShiftMask
        return KeyboardSide.All;
    }

    /// <inheritdoc />
    public override LogicalKeyboardKey? NumpadKey(int keyCode)
    {
        return KeyboardMaps.KGlfwNumpadMap.GetValueOrDefault(keyCode);
    }

    /// <inheritdoc />
    public override LogicalKeyboardKey? LogicalKey(int keyCode)
    {
        return KeyboardMaps.KGlfwToLogicalKey.GetValueOrDefault(keyCode);
    }

    /// <inheritdoc />
    public override long PlatformPlane => LogicalKeyboardKey.GlfwPlane;
}

/// <summary>Helper class that uses GTK-specific key mappings.</summary>
